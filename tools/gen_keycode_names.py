#!/usr/bin/env python3
"""Generates src/godot/keycode_names.inc from Godot 4.1.4's own key-name table.

    python tools/gen_keycode_names.py <keyboard.h> <keyboard.cpp>

keycode_get_string (core/os/keyboard.cpp) names a key by the _keycodes[]
table and falls back to String::chr(code). KeyRebinding shows these names on
the controls screen, so the port uses the same table, generated rather than
retyped. The two files come from
https://raw.githubusercontent.com/godotengine/godot/4.1.4-stable/core/os/.
Engine data, not game content.
"""
import os
import re
import sys


def main(h_path, cpp_path):
    h = open(h_path, encoding="utf-8").read()
    cpp = open(cpp_path, encoding="utf-8").read()
    enum_body = h[h.index("enum class Key {"):]
    enum_body = enum_body[:enum_body.index("};")]
    values = {}
    for name, expr in re.findall(r"^\s*([A-Z0-9_]+)\s*=\s*([^,]+),", enum_body, re.M):
        expr = expr.strip()
        m = re.match(r"SPECIAL\s*\|\s*(0x[0-9A-Fa-f]+)", expr)
        if expr == "(1 << 22)":
            values[name] = 1 << 22
        elif m:
            values[name] = (1 << 22) | int(m.group(1), 16)
        elif re.match(r"0x[0-9A-Fa-f]+$", expr) or expr.isdigit():
            values[name] = int(expr, 0)
    table = cpp[cpp.index("_keycodes[] = {"):]
    table = table[:table.index("{Key::NONE")]
    rows = re.findall(r"\{Key::([A-Z0-9_]+)\s*,\s*\"([^\"]*)\"\}", table)
    out = ["// Generated by tools/gen_keycode_names.py from Godot 4.1.4",
           "// core/os/keyboard.cpp _keycodes[] (keycode_get_string). Do not edit.",
           "// { keycode, name }"]
    missing = []
    for name, text in rows:
        if name not in values:
            missing.append(name)
            continue
        out.append('{%d, "%s"},' % (values[name], text))
    dest = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "src", "godot", "keycode_names.inc")
    open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("wrote %s: %d names%s" % (dest, len(out) - 3, (", unresolved " + str(missing)) if missing else ""))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
